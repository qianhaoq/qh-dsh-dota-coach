test('material import, evidence-linked knowledge and original source remain readable', async ({
  page,
}) => {
  await page.goto('/?legacy=1')
  await page.getByRole('tab', { name: '知识库', exact: true }).click()
  await page.getByRole('button', { name: '导入材料', exact: true }).click()
  await page.getByLabel('来源 ID', { exact: true }).fill('user:browser-material')
  await page.getByLabel('材料标题', { exact: true }).fill('地图观察材料')
  await page.getByLabel('原文定位（时间戳、段落或 URL）').fill('第 2 段')
  await page
    .getByLabel('正文', { exact: true })
    .fill(
      '过河之前先检查小地图，确认友军是否能够及时到达。这里记录的是观察规则，不能推断敌方真实视野。',
    )
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('combobox', { name: '搜索', exact: true }).selectOption('sources')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await page.getByRole('button', { name: /地图观察材料/ }).click()
  await expect(page.locator('.dota-body')).toContainText('不能推断敌方真实视野')
  await page.screenshot({ path: 'test-results/knowledge-source.png', fullPage: true })
})
