import { test, expect } from '@playwright/test'
test('no account, unavailable replay and no source plugin remain usable', async ({ page }) => {
  await page.goto('/?legacy=1')
  await expect(page.getByText('先设置账号，或直接输入对局 ID 开始复盘。')).toBeVisible()
  await page.getByRole('tab', { name: '复盘', exact: true }).click()
  await page.getByLabel('对局 ID', { exact: true }).fill('424243')
  await page.getByRole('button', { name: '读取', exact: true }).click()
  await expect(page.getByText('此窗口没有可对齐的坐标；仍可根据比赛事件复盘。')).toBeVisible()
  await page.getByRole('button', { name: '提取轨迹' }).click()
  await expect(page.getByRole('alert')).toContainText('Fetch a replay first')
  await page.getByRole('tab', { name: '知识库', exact: true }).click()
  await page.getByRole('button', { name: '导入材料', exact: true }).click()
  await expect(page.getByText('未安装取材插件时，可在这里导入字幕或正文。')).toBeVisible()
})
test('review window, evidence-linked learning, one training goal and checkin work together', async ({
  page,
}) => {
  await page.goto('/?legacy=1')
  await page.getByRole('tab', { name: '复盘', exact: true }).click()
  await page.getByLabel('对局 ID', { exact: true }).fill('424242')
  await page.getByRole('button', { name: '读取', exact: true }).click()
  await expect(page.getByRole('img', { name: '战场坐标' }).locator('circle')).not.toHaveCount(0)
  await page.getByLabel('开始（秒）').fill('130')
  await page.getByLabel('结束（秒）').fill('150')
  await expect(page.locator('.dota-events li')).toHaveCount(0)
  await page.getByLabel('开始（秒）').fill('100')
  await page.getByLabel('结束（秒）').fill('140')
  await expect(page.locator('.dota-events li')).not.toHaveCount(0)
  await page.getByLabel('针对当前窗口的问题').fill('这里为什么应该等队友？')
  await page.getByRole('button', { name: '问教练', exact: true }).click()
  await expect(page.getByTestId('draft')).toContainText('match_id=424242')
  await page.getByLabel('本次复盘标题').fill('过河前检查')
  await page.getByLabel('学员当时的判断').fill('我想尽快推进，但没有确认队友位置。')
  await page.getByLabel('触发条件', { exact: true }).fill('过河前')
  await page.getByLabel('行动规则', { exact: true }).fill('先检查小地图和队友位置')
  await page.getByLabel('检查方式', { exact: true }).fill('下一局回看三次过河决策')
  await page.getByLabel('复盘结论', { exact: true }).fill('本次只练习过河前检查队友位置。')
  await page.getByRole('button', { name: '保存复盘和唯一训练目标', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()
  await page.getByRole('tab', { name: '训练', exact: true }).click()
  await expect(page.getByRole('heading', { name: '过河前检查', exact: true })).toHaveCount(1)
  await page.getByLabel('对局 ID', { exact: true }).fill('424244')
  await page.getByLabel('执行说明').fill('在三次过河前都检查了队友位置。')
  await page.getByLabel('本次已执行').check()
  await page.getByRole('button', { name: '记录执行', exact: true }).click()
  await expect(page.getByText('记录执行 (1)', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/review-training.png', fullPage: true })
})
